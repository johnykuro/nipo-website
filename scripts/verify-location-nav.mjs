import { execFileSync } from 'node:child_process';
import { mkdirSync } from 'node:fs';
import assert from 'node:assert/strict';
// Run against scripts/qa-server.mjs; all signup and third-party services are mocked.
const bin=process.env.AGENT_BROWSER_BIN;
if (!bin) throw new Error('Set AGENT_BROWSER_BIN to the installed agent-browser executable.');
mkdirSync('tmp/qa', {recursive:true});
const run=(...args)=>{let output;try{output=execFileSync(bin,['--session','nipo-nav','--json',...args],{encoding:'utf8',timeout:30000});}catch(error){if(error.code!=='ETIMEDOUT'||!error.stdout||!JSON.parse(error.stdout).success)throw error;output=error.stdout;}const r=JSON.parse(output);assert(r.success,r.error);return r.data;};
const ev=s=>run('eval',s).result;
const open=p=>run('open','http://127.0.0.1:4323'+p);
open('/');
ev("localStorage.setItem('nipo-cookie-consent',JSON.stringify({version:1,analytics:false,marketing:false,expires:Date.now()+86400000}))");
open('/');
run('set','viewport','1440','1000');
assert(ev("document.body.innerText.includes('Harrogate Coming Soon') && !document.querySelector('astro-error-overlay, vite-error-overlay')"));
assert.equal(ev("document.querySelector('.locations-heading').innerText"), 'Find Your NIPO');
assert(!ev("document.querySelector('.locations-heading .label')"));
assert.equal(ev("document.querySelector('.desktop-nav a[href=\"/locations/newcastle/\"]').textContent"), 'Newcastle Quayside');
assert(!ev("document.querySelector('.footer-address').innerText.includes('Open')"));
run('hover','.desktop-nav summary');
assert(ev("document.querySelector('.desktop-nav details').open"));
const gap=ev("(() => {const r=document.querySelector('.desktop-nav summary').getBoundingClientRect(); return {x:r.x+r.width/2,y:r.bottom+6}})()");
run('mouse','move',String(Math.round(gap.x)),String(Math.round(gap.y)));
assert(ev("document.querySelector('.desktop-nav details').open"));
run('hover','.desktop-nav a[href="/locations/harrogate/"]');
assert(ev("document.querySelector('.desktop-nav details').open"));
run('hover','.hero-content h1');
assert(!ev("document.querySelector('.desktop-nav details').open"));
run('hover','.desktop-nav summary');run('click','.desktop-nav summary');
run('hover','.hero-content h1');
assert(ev("document.querySelector('.desktop-nav details').open"));
run('click','.desktop-nav summary');
assert(!ev("document.querySelector('.desktop-nav details').open"));
run('hover','.hero-content h1');
console.log('PASS desktop hover, pointer gap, leave dismissal, click pin and second-click close');
assert(ev("!!(document.querySelector('[data-gallery-rail]').compareDocumentPosition(document.querySelector('.locations-section')) & Node.DOCUMENT_POSITION_FOLLOWING)"));
run('focus','.desktop-nav summary');run('press','Enter');
assert(ev("document.querySelector('.desktop-nav details').open"));
run('press','Tab');assert(ev("document.activeElement.getAttribute('href')==='/locations/newcastle/'"));
run('press','Escape');assert(!ev("document.querySelector('.desktop-nav details').open"));
assert(ev("document.activeElement.matches('.desktop-nav summary')"));
run('click','.desktop-nav summary');run('screenshot','tmp/qa/location-dropdown-desktop.png');
run('click','.hero-content h1');assert(!ev("document.querySelector('.desktop-nav details').open"));
run('click','.desktop-nav summary');run('focus','.header-book');assert(!ev("document.querySelector('.desktop-nav details').open"));
run('click','.desktop-nav summary');run('click','.desktop-nav a[href="/locations/harrogate/"]');
assert.equal(ev('location.pathname'),'/locations/harrogate/');
assert.equal(ev("document.querySelector('.desktop-nav a[aria-current]').textContent.trim().replace(/\\s+/g,' ')"),'HarrogateComing soon');
console.log('PASS gallery order, desktop click/keyboard navigation, Escape, outside click, focus dismissal and active location');
run('set','viewport','390','844');
run('click','[data-menu-toggle]');run('click','[data-mobile-menu] summary');
assert(ev("document.querySelector('[data-mobile-menu]').open && document.querySelector('[data-mobile-menu] details').open"));
assert(!ev('document.documentElement.scrollWidth>innerWidth'));
run('screenshot','tmp/qa/location-dropdown-mobile.png');
run('press','Tab');run('press','Escape');
assert(ev("document.querySelector('[data-mobile-menu]').open && !document.querySelector('[data-mobile-menu] details').open"));
run('click','[data-mobile-menu] summary');run('click','[data-mobile-menu] details a[href="/locations/newcastle/"]');
assert.equal(ev('location.pathname'),'/locations/newcastle/');
console.log('PASS mobile disclosure, Escape and Newcastle navigation');
ev("fetch('/__qa/mode?value=no-js').then(r=>r.json())");open('/');
run('click','.no-js-nav summary');run('click','.no-js-nav details a[href="/locations/harrogate/"]');
assert.equal(ev('location.pathname'),'/locations/harrogate/');
ev("fetch('/__qa/mode?value=success').then(r=>r.json())");
console.log('PASS dropdown links without JavaScript');
ev("fetch('/__qa/mode?value=success').then(r=>r.json())");open('/');
for (const width of [390, 768, 1440]) {
  run('set','viewport',String(width),'1000');
  const spacing=ev("(() => {const welcome=getComputedStyle(document.querySelector('.welcome'));const locations=getComputedStyle(document.querySelector('.locations-section'));const rail=getComputedStyle(document.querySelector('.rail-section'));return {top:welcome.paddingTop,bottom:welcome.paddingBottom,locations:locations.paddingTop,rail:rail.paddingBottom,overflow:document.documentElement.scrollWidth>innerWidth}})()");
  assert.equal(spacing.top,spacing.bottom);assert.equal(spacing.top,spacing.locations);assert.equal(spacing.rail,'0px');assert(!spacing.overflow);
}
run('set','viewport','1440','1000');
ev("document.querySelector('.welcome').scrollIntoView({behavior:'instant'})");
run('wait','600');run('screenshot','tmp/qa/home-spacing-desktop.png');
run('set','viewport','390','844');
ev("document.querySelector('.locations-section').scrollIntoView({behavior:'instant'})");
run('wait','600');run('screenshot','tmp/qa/home-locations-mobile.png');
assert.deepEqual(run('errors'), {errors:[]});
console.log('PASS homepage spacing and no overflow at mobile, tablet and desktop; no browser errors');
run('close');
